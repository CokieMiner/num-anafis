// --- Precision control ---

pub(in crate::float_ops) const fn get_precision() -> u32 {
    53
} // f64 mantissa bits

// --- Construction & conversion ---

#[inline]
#[allow(
    clippy::cast_precision_loss,
    reason = "Lossy int-to-float; caller must restrict magnitude to ≤ 2^53 for exactness"
)]
pub(in crate::float_ops) fn from_int(value: &IntType) -> BackingFloat {
    *value as f64
}

#[inline]
pub(in crate::float_ops) const fn from_f32(value: f32) -> BackingFloat {
    value as f64
}

#[inline]
pub(in crate::float_ops) const fn from_f64(value: f64) -> BackingFloat {
    value
}

/// Convert i64 to f64. Exact for |value| ≤ 2^53; loses LSB precision for larger magnitudes.
#[inline]
#[allow(
    clippy::cast_precision_loss,
    reason = "i64→f64 loses LSBs for |value| > 2^53; callers must accept this"
)]
pub(in crate::float_ops) const fn from_i64(value: i64) -> BackingFloat {
    value as f64
}

#[inline]
#[allow(
    clippy::cast_precision_loss,
    clippy::cast_possible_truncation,
    reason = "Precision loss and truncation are intentional for float-to-int conversions"
)]
pub(in crate::float_ops) fn to_int(value: &BackingFloat) -> Option<IntType> {
    (value.fract() == 0.0 && *value >= i64::MIN as f64 && *value < i64::MAX as f64)
        .then_some(*value as i64)
}

pub(in crate::float_ops) fn pi() -> BackingFloat {
    PI
}

pub(in crate::float_ops) fn nan() -> BackingFloat {
    f64::NAN
}


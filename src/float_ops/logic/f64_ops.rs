pub(in crate::float_ops) type BackingFloat = f64;

// ============================================================================
// Math bridge — libm (no_std) vs platform std math
// ============================================================================

macro_rules! math_bridge {
    ($(fn $name:ident($val:ident: f64) -> f64 = $libm:ident as $std:ident;)*) => {
        #[cfg(not(feature = "std"))]
        mod math {
            $(pub(super) fn $name($val: f64) -> f64 { libm::$libm($val) })*
            pub(super) fn atan2(y: f64, x: f64) -> f64 { libm::atan2(y, x) }
            pub(super) fn pow(a: f64, b: f64) -> f64 { libm::pow(a, b) }
        }
        #[cfg(feature = "std")]
        mod math {
            $(pub(super) fn $name($val: f64) -> f64 { f64::$std($val) })*
            pub(super) fn atan2(y: f64, x: f64) -> f64 { y.atan2(x) }
            pub(super) fn pow(a: f64, b: f64) -> f64 { a.powf(b) }
        }
    };
}

